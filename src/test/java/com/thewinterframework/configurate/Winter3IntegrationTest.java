package com.thewinterframework.configurate;

import com.google.inject.Guice;
import com.google.inject.Injector;
import com.thewinterframework.component.ComponentManager;
import com.thewinterframework.component.context.ComponentContext;
import com.thewinterframework.component.meta.ComponentDescriptor;
import com.thewinterframework.configurate.module.ConfigurationReloads;
import com.thewinterframework.plugin.WinterPlugin;
import com.thewinterframework.service.ReloadServiceManager;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.tools.DiagnosticCollector;
import javax.tools.JavaFileObject;
import javax.tools.ToolProvider;
import java.lang.reflect.Proxy;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;

import static org.junit.jupiter.api.Assertions.*;

class Winter3IntegrationTest {
    @TempDir Path directory;

    @Test
    void generatesConfigurationAndExternalReloadComponentWithWinter3() throws Exception {
        final var sources = Files.createDirectories(directory.resolve("sources/example"));
        final var boot = sources.resolve("TestPlugin.java");
        Files.writeString(boot, """
                package example;
                @com.thewinterframework.plugin.WinterBootPlugin
                public abstract class TestPlugin implements com.thewinterframework.plugin.WinterPlugin {}
                """);
        final var config = sources.resolve("Settings.java");
        Files.writeString(config, """
                package example;
                @com.thewinterframework.configurate.config.Configurate("settings")
                @org.spongepowered.configurate.objectmapping.ConfigSerializable
                public class Settings { public String message = "ready"; }
                """);
        final var output = Files.createDirectories(directory.resolve("classes"));
        final var generated = Files.createDirectories(directory.resolve("generated"));
        final var diagnostics = new DiagnosticCollector<JavaFileObject>();
        final var compiler = ToolProvider.getSystemJavaCompiler();
        try (final var files = compiler.getStandardFileManager(diagnostics, null, null)) {
            final var classpath = System.getProperty("configuration.test.classpath");
            final var options = List.of("-classpath", classpath, "-processorpath", classpath,
                    "-d", output.toString(), "-s", generated.toString());
            assertTrue(compiler.getTask(null, files, diagnostics, options, null,
                    files.getJavaFileObjectsFromPaths(List.of(boot, config))).call(),
                    () -> diagnostics.getDiagnostics().toString());
        }
        final var provider = Files.readString(generated.resolve(
                "example/autogenerated_winter_modules/ProcessorModuleProvider.java"));
        assertTrue(provider.contains("ConfigurateModule.class"));
        assertTrue(provider.contains("ConfigurationsModule.class"));
        assertTrue(provider.contains("ComponentModule.class"));
        final var wire = Files.readString(generated.resolve(
                "example/autogenerated_winter_modules/ComponentListWire.java"));
        assertTrue(wire.contains("ConfigurationReloads.class"));
    }

    @Test
    void reloadsCallbacksThroughWintersComponentDecoratorWithoutLegacyServiceManager() throws Exception {
        final var injectorRef = new AtomicReference<Injector>();
        final var plugin = (WinterPlugin) Proxy.newProxyInstance(getClass().getClassLoader(),
                new Class<?>[]{WinterPlugin.class}, (instance, method, args) -> {
                    if (method.getName().equals("getInjector")) return injectorRef.get();
                    throw new UnsupportedOperationException(method.getName());
                });
        final var manager = new ComponentManager();
        manager.registerComponent(new ComponentContext(plugin, ComponentDescriptor.from(ConfigurationReloads.class)), List.of());
        manager.loadDecorators(plugin);
        final var reloads = new ConfigurationReloads();
        final var calls = new AtomicInteger();
        reloads.register(calls::incrementAndGet);
        injectorRef.set(Guice.createInjector(binder -> binder.bind(ConfigurationReloads.class).toInstance(reloads)));
        final var reloadManager = new ReloadServiceManager(manager, plugin);
        assertTrue(reloadManager.reload().result());
        assertEquals(1, calls.get());
        reloads.clear();
        assertTrue(reloadManager.reload().result());
        assertEquals(1, calls.get());
    }
}
